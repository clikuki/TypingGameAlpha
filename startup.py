def print_animation():
    startup_strings = get_logo_strings()

    size = 0
    for row in startup_strings:
        row_size = len(row)
        if size < row_size:
            size = row_size
            
    for i in range(size + len(startup_strings) * 2):
        clear_screen()

        curr_str = ""
        for j,row in enumerate(startup_strings):
            row_slice_idx = i-j*2

            if row_slice_idx <= 0:
                break
            
            curr_str += row[:row_slice_idx] + "\n"

        print(curr_str)
        sleep(0.01)

    sleep(0.5)

def print_fast():
    startup_strings = get_logo_strings()
    print("\n".join(startup_strings) + "\n")
